# Write training data to temp file
with tempfile.NamedTemporaryFile("w", encoding="utf-8", delete=False, suffix=".train") as f:
    train_path = f.name
    # Positive samples
    for text in positive_samples:
        clean = " ".join(text.split())
        if clean:
            f.write(f"__label__wiki {clean}\n")
    # Negative samples
    for text in negative_samples:
        clean = " ".join(text.split())
        if clean:
            f.write(f"__label__cc {clean}\n")

# Train fasttext supervised model
model = fasttext.train_supervised(
    input=train_path,
    lr=0.5,
    epoch=35,
    wordNgrams=2,
    bucket=200000,
    dim=50,
    loss="softmax",
)

# Test on test fixtures
